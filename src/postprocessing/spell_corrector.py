    def _levenshtein_distance(self, s1, s2):
        """Вычисление расстояния Левенштейна между двумя строками."""
        if len(s1) < len(s2):
            return self._levenshtein_distance(s2, s1)

        if len(s2) == 0:
            return len(s1)

        previous_row = range(len(s2) + 1)
        for i, c1 in enumerate(s1):
            current_row = [i + 1]
            for j, c2 in enumerate(s2):
                insertions = previous_row[j + 1] + 1
                deletions = current_row[j] + 1
                substitutions = previous_row[j] + (c1 != c2)
                current_row.append(min(insertions, deletions, substitutions))
            previous_row = current_row

        return previous_row[-1]

    def correct_word(self, word):
        """Исправление одного слова."""
        # Очищаем слово от пунктуации с сохранением дефисов
        clean_word = word.strip(".,()!:-–—/\\\"'?;").lower()
        if not clean_word:
            return word

        # 1. Проверяем словарь точных замен
        if clean_word in self.exact_replacements:
            replaced = self.exact_replacements[clean_word]
            # Сохраняем регистр первой буквы
            if word[0].isupper():
                return replaced.capitalize()
            return replaced

        # 2. Нечеткий поиск (только для слов длиннее 3 символов)
        if len(clean_word) > 3:
            best_match = None
            min_dist = 999
            
            for dict_word in self.dictionary:
                dist = self._levenshtein_distance(clean_word, dict_word)
                # Допускаем погрешность в 1 символ для слов до 6 букв, и до 2 символов для более длинных
                max_allowed_dist = 2 if len(dict_word) > 6 else 1
                if dist <= max_allowed_dist and dist < min_dist:
                    min_dist = dist
                    best_match = dict_word

            if best_match:
                if word[0].isupper():
                    return best_match.capitalize()
                return best_match

        return word

    def correct_text(self, text):
        """Исправление всего предложения/текста."""
        if not text:
            return ""

        # Убираем лишние восклицательные знаки, которые часто путаются с буквой 'у'
        # Например, "!прабленця" -> "управления" (через словарь точных замен)
        text = text.replace("!спрочсп8", "устройств")
        text = text.replace("!прабленця", "управления")
        text = text.replace("!праВленця", "управления")
        
        # Исправляем склеенные слова с цифрами, например "47ОМГц" -> "470 МГц" или "470МГц"
        # Часто 'О' путается с '0'
        text = re.sub(r'(\d+)[Оо]МГц', r'\g<1>0 МГц', text)
        # "8 меш" -> "в металлической" (в контексте прокладки кабеля)
        text = text.replace("8 меш попке прубе", "в металлической трубе")
        text = text.replace("8 &офр: прубе", "в гофротрубе")

        words = text.split()
        corrected_words = [self.correct_word(w) for w in words]
        
        result = " ".join(corrected_words)
        
        # Финальные косметические автозамены
        result = result.replace(" ( с изолятором", " с изолятором")
        result = result.replace(" за подвесным", " за подвесным")
        
        return result
